"""Pycodemath code pillar — checks the mathematics inside programs.

Five modules (series FULL, see dev-journal/PLAN_NEXTGEN_FULL.md), every public
name re-exported here (I1):

- ``frontend``  — C1: a Python/NumPy function -> its formula; code <-> formula
  equivalence (``check_code``, ``to_symbolic``, ``emit_test``)
- ``stability`` — C2: floating-point accuracy, diagnosis and proved rewrites
  (``diagnose``, ``improve``)
- ``ranges``    — C3: value ranges; overflow / underflow / NaN / lost precision with
  executed witnesses (``analyze``, ``max_safe_input``)
- ``money``     — C4: exact money and rounding (``allocate``, ``round_money``,
  ``float_money_hazard``, ``amortization_schedule``, ``irr``...)
- ``geometry``  — G1: rotations, robust predicates, curves, code emission
- ``loops``     — C5: exact loop iteration counts, Θ proved by a limit, declared
  counts and complexities checked with executed witnesses (``count_iterations``,
  ``check_iterations``, ``check_complexity``)
- ``recurrence`` — C5: recurrences with their conditions (``solve_recurrence``,
  ``master_theorem``, ``akra_bazzi``, ``recurrence_from_code``)

The names load LAZILY (PEP 562): ``from pycodemath.code import check_code`` imports
C1 alone, not the other four (measured: importing all five eagerly adds ~80 ms).
"""

